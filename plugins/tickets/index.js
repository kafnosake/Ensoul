/**
 * tickets —— 派单队列监视。
 *
 * 收件箱是 dispatch 的（`.ensoul/state/dispatch.inbox.json`）：谁给谁派了什么活、
 * 走到谁手上、交没交。那些事实一直躺在文件里，但只有发起人自己敲 /inbox 才看得见 ——
 * 想"一眼扫全公司欠着几件活"就没有地方了。这个插件就补这一块：把那份收件箱摊成一块看板。
 *
 * ══ 撤单只往命令队列里放一条 ═════════════════════════════════════════════════
 *
 * 收件箱归 dispatch 写；这里**不自己改它** —— 两个写者盯同一个文件，迟早有一条被盖掉
 * （丢的不是一条记录，是"一件事没人交"，而且不报错）。所以撤单 / 恢复是往 dispatch 的
 * **命令队列**里放一条（命令文件由面板写，每条带 panelId 和 token），改账由收件箱的主人做。
 *
 * ══ 它不管"叫醒谁" ════════════════════════════════════════════════════════
 *
 * 交付到货要不要把发起人叫起来，是 delivery-alert 的事（那要花掉一轮模型调用，
 * 用户得能单独关掉）。这里只是显示器，不打扰任何人。
 */

module.exports = {
  name: 'tickets',
  description: t('派单队列监视 + 手动撤单：把 dispatch 的收件箱摊成一块看板 —— 谁欠谁一件活、等了多久、交了什么，作废的单在这里划掉'),

  /** 声明是纯数据（要过 IPC），必须在 module.exports 里 —— 放外面整个插件加载不了 */
  panel: {
    kind: 'tickets',
    label: t('派单队列'),
    hint: t('盯着派单收件箱：未交付的活、等了多久、谁交了什么，还能手动撤单'),
    title: t('派单队列'),
    body: 'messages',
    look: { showChat: true, accent: '#e0954b' },
  },

  setup(api) {
    api.log(t('派单队列监视就绪（读收件箱；撤单走 dispatch 的命令队列）'));
  },
};
