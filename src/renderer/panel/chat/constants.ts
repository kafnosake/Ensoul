/**
 * 对话面板里几个"两边都要知道"的数字与键。
 * 摆在一个文件里，免得改了一处、另一处还按老值算。
 */

/** 悬停摊开的那张卡有多宽。CSS 里 .note-pop 的 width 必须和它一致 */
export const PEEK_W = 320;

/**
 * 会话列的宽度（见 useSessionWidth）。
 *
 * 没有它的时候，消息在一整块面板里从左铺到右 —— 一行长到读不下去。
 * 默认给一条**居中**的列，两边留白：会话区那两条几乎看不见的边，
 * 一开始就站在这里。
 */
export const SESSION_W = 760;
/** 再窄就不成句了 */
export const SESSION_W_MIN = 400;
/**
 * 一次渲染多少条消息。更早的**先不放进文档**，在上面挂一个按钮，点一下再放一段。
 *
 * 这是"长对话拖宽度就卡死"的正解：卡的不是宽度那个数字，是这一列里**有多少条 DOM**。
 * 上千条全挂着，改一次宽度就要把上千条重新排版一遍 —— 几十毫秒起步，拖起来一帧一卡。
 * 只留最近这一段，DOM 从上千降下来，拖宽度、滚动、流式输出跟着全都轻下来
 * （只给最近的，更早的要手动点开）。
 *
 * 100 条：一屏大概十条上下，这是"往上滚十屏"的量 —— 绝大多数时候读不到那么远，
 * 真读到了点一下顶上那个按钮就是。数字调大的代价是每次重排的条数跟着涨，
 * 所以就停在这个量级，别再往上加。
 */
export const PAGE = 100;
/**
 * 列两边至少留这么宽的留白。
 *
 * 便签那条刻度就住在里面 —— 所以列再宽也压不到刻度上，两者互不干涉：
 * **便签不是一栏，会话列也不是为了给便签让路才变窄的。**
 */
export const SESSION_GUTTER = 22;

/**
 * 离底部多近算"还在跟着"（像素）。
 *
 * 这个数是给**用户往上滚**用的，不是给内容变长用的：内容在下面长高时 scrollTop
 * 一动不动，光看距离会把它误判成"用户往上翻了"。所以判据是"往上滚 **且** 已经离开
 * 底部这么远"——小幅抖动（一行字、一次滚轮的余量）不算离开。
 */
export const FOLLOW_SLACK = 80;

